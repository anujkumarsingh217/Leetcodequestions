/**
 * Definition for singly-linked list.
 * class ListNode {
 *     int val;
 *     ListNode next;
 *     ListNode(int x) {
 *         val = x;
 *         next = null;
 *     }
 * }
 */
public class Solution {
    public boolean hasCycle(ListNode head) {
        ListNode a = head;  // slow
        ListNode b = head;  // fast

        while (b != null && b.next != null) {
            a = a.next;          // 1 step
            b = b.next.next;     // 2 steps

            if (a == b) {
                return true;
            }
        }

        return false;
    }
}

